/// 문서의 한 조항. `· `로 시작하는 문단은 글머리표 목록으로 그린다.
class DocSection {
  final String title;
  final List<String> paragraphs;

  const DocSection({required this.title, required this.paragraphs});
}

/// 약관처럼 긴 문서 한 편.
class AppDocument {
  /// 화면 제목.
  final String title;

  /// 맨 위 한두 문장 요약.
  final String summary;

  /// 운영자·시행일·문의처 같은 머리 정보.
  final List<String> meta;

  final List<DocSection> sections;

  /// 조문보다 먼저 읽는 쉬운 말 요약. 없으면 비워 둔다.
  final List<DocSection> plain;

  const AppDocument({
    required this.title,
    required this.summary,
    required this.meta,
    required this.sections,
    this.plain = const [],
  });
}

